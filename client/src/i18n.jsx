const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem("krishisetu-language") || "en");
  useEffect(() => {
    document.documentElement.lang = language === "kn" ? "kn" : "en";
  }, [language]);
  const changeLanguage = (value) => {
    localStorage.setItem("krishisetu-language", value);
    setLanguage(value);
  };
  const value = useMemo(() => ({ language, changeLanguage, t: (key) => dictionary[language][key] || dictionary.en[key] || key }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
